#!/usr/bin/env python3
"""Audit docs/API-INVENTORY.md against the implemented sources.

For every *type-level* symbol in the crawled inventory (structs, classes,
enums, protocols, typealiases — member/property/function pages are out of
scope: the checklist granularity is per type), scan `Sources/LinuxCombine` for a
matching declaration and regenerate `docs/API-INVENTORY.md` with
`[x]` (implemented) / `[ ]` (backlog) plus a summary header.

Usage:
    python3 Tools/audit_inventory.py
"""

import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "docs" / "api-inventory.json"
MARKDOWN = ROOT / "docs" / "API-INVENTORY.md"
SOURCES = ROOT / "Sources" / "LinuxCombine"

DECL_RE = re.compile(
    r"\b(?:public\s+|internal\s+)?(?:final\s+|@frozen\s+|@propertyWrapper\s+)*"
    r"(?:struct|class|enum|protocol|typealias|associatedtype)\s+([A-Z]\w*)\b"
)

# External-framework pages crawled for their Combine sections.
EXTERNAL_PREFIXES = ("documentation/Dispatch/", "documentation/Foundation/")


def is_type_page(path: str, rec: dict) -> bool:
    if rec.get("kind") != "symbol":
        return False  # articles are documentation, not API
    name = short(path)
    if not name:
        return False
    last = name.split("/")[-1]
    if not re.match(r"^[A-Z]", last):
        return False  # properties/functions: below type granularity
    if "(" in last:
        return False  # method pages
    return True


def short(path: str) -> str:
    if path.startswith("documentation/Combine/"):
        return path[len("documentation/Combine/"):].removesuffix(".json")
    if path.startswith(EXTERNAL_PREFIXES):
        return path[len("documentation/"):].removesuffix(".json")
    return ""


def load_declared_symbols() -> set:
    symbols = set()
    for file in sorted(SOURCES.rglob("*.swift")):
        text = file.read_text(encoding="utf-8")
        # strip line comments to avoid matching doc prose
        text = re.sub(r"//.*", "", text)
        symbols.update(DECL_RE.findall(text))
        # External scheduler conformances are declared as extensions
        # (`extension DispatchQueue: Scheduler`) — their DocC type pages
        # are Combine-facing and must count as implemented.
        symbols.update(re.findall(
            r"extension\s+([A-Za-z_][\w.]*)\b", text))
    return symbols


def group_of(name: str) -> str:
    head = name.split("/")[0]
    if "/" not in name:
        return "Top-level types"
    if head in ("Publishers", "Subscribers", "Subscriptions"):
        return head + ".*"
    if name.startswith(("Dispatch/", "Foundation/")):
        return "External: Dispatch/Foundation Combine extensions"
    if head in ("Subscribers",):
        return "Subscribers.*"
    return "Nested types"


def main() -> int:
    inv = json.loads(INVENTORY.read_text(encoding="utf-8"))
    declared = load_declared_symbols()

    rows = []
    for path, rec in inv["pages"].items():
        if not is_type_page(path, rec):
            continue
        name = short(path)
        # DocC appends provenance suffixes: "Recording-swift.struct",
        # "Output-swift.typealias" — strip before the declared lookup.
        simple = re.sub(r"-swift\.(struct|class|enum|protocol|typealias)$", "",
                        name.split("/")[-1])
        implemented = simple in declared
        decls = rec.get("decls") or []
        rows.append({
            "name": name,
            "simple": simple,
            "implemented": implemented,
            "decl": decls[0].replace("\n", " ") if decls else rec.get("title", ""),
            "members": sum(len(s.get("members", [])) for s in rec.get("sections", [])),
        })

    done = sum(1 for r in rows if r["implemented"])
    total = len(rows)

    groups = {}
    for r in rows:
        groups.setdefault(group_of(r["name"]), []).append(r)

    lines = [
        "# Combine API inventory",
        "",
        f"Generated by `Tools/audit_inventory.py` from Apple's official DocC JSON "
        f"({datetime.now(timezone.utc).isoformat(timespec='seconds')}). "
        f"**{done}/{total} type-level symbols implemented "
        f"({done * 100 // total}%).**",
        "",
        "`[x]` = declared in `Sources/LinuxCombine` (behavior pinned by the test gates);",
        "`[ ]` = backlog (see docs/QUIRKS.md §D and the reassessment note).",
        "Checkbox granularity is per type; member lists live in",
        "`docs/api-inventory.json` under each type's `sections`.",
        "",
    ]
    order = [
        "Top-level types",
        "Publishers.*",
        "Subscribers.*",
        "External: Dispatch/Foundation Combine extensions",
        "Nested types",
    ]
    for group in order:
        items = groups.get(group)
        if not items:
            continue
        gdone = sum(1 for r in items if r["implemented"])
        lines.append(f"## {group} ({gdone}/{len(items)})")
        lines.append("")
        for r in sorted(items, key=lambda r: r["name"]):
            box = "x" if r["implemented"] else " "
            extra = f" · {r['members']} members" if r["members"] else ""
            lines.append(f"- [{box}] `{r['name']}` — `{r['decl']}`{extra}")
        lines.append("")

    # any unexpected groups
    for group, items in sorted(groups.items()):
        if group in order:
            continue
        gdone = sum(1 for r in items if r["implemented"])
        lines.append(f"## {group} ({gdone}/{len(items)})")
        lines.append("")
        for r in sorted(items, key=lambda r: r["name"]):
            box = "x" if r["implemented"] else " "
            lines.append(f"- [{box}] `{r['name']}` — `{r['decl']}`")
        lines.append("")

    MARKDOWN.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"implemented {done}/{total} ({done * 100 // total}%)")
    print("backlog symbols:")
    for r in sorted((r for r in rows if not r["implemented"]), key=lambda r: r["name"]):
        print("  [ ]", r["name"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
