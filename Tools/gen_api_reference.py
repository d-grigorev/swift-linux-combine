#!/usr/bin/env python3
"""Generate docs/API-REFERENCE.md from the DocC crawl inventory.

The reference is derived — never hand-edited — from
`docs/api-inventory.json` (see `Tools/crawl_combine_api.py`), so it can
never drift from the declaration-verified implementation
(`Tools/verify_decls.py`). Every official type the library implements
is listed with its verified member signatures.

Usage:
    python3 Tools/gen_api_reference.py           # write the reference
    python3 Tools/gen_api_reference.py --check   # exit 1 if it is stale
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "docs" / "api-inventory.json"
OUTPUT = ROOT / "docs" / "API-REFERENCE.md"

# Group classification ------------------------------------------------------
CORE = {
    "Publisher", "Subscriber", "Subscribers", "Subscription", "Subscriptions",
    "Cancellable", "AnyCancellable", "AnyPublisher", "AnySubscriber",
    "CombineIdentifier", "CustomCombineIdentifierConvertible",
    "ConnectablePublisher", "TopLevelEncoder", "TopLevelDecoder",
}
SCHEDULERS = {"Scheduler", "SchedulerTimeIntervalConvertible",
              "ImmediateScheduler"}
SUBJECTS = {"Subject", "PassthroughSubject", "CurrentValueSubject", "Record"}
VALUE_PUBLISHERS = {"Just", "Empty", "Fail", "Deferred", "Future"}
STATE = {"Published", "ObservableObject", "ObservableObjectPublisher"}
ASYNC = {"AsyncPublisher", "AsyncThrowingPublisher"}

EXTERNAL_SCHEDULERS = {
    "documentation/Foundation/RunLoop": "Schedulers",
    "documentation/Foundation/OperationQueue": "Schedulers",
    "documentation/Dispatch/DispatchQueue": "Schedulers",
}

GROUP_ORDER = [
    "Core", "Schedulers", "Subjects", "Value publishers", "State",
    "Async interop", "Subscribers", "Publishers", "Foundation bridges",
]

# The Just/Publishers.Sequence operator sugar is listed only on DocC
# *article* extension pages (QUIRKS C10) — merge them into their types.
EXTENSION_ARTICLES = {
    "Just": "documentation/Combine/Just-Publisher-Operators.json",
    "Publishers.Sequence":
        "documentation/Combine/Publishers-Sequence-Publisher-Operators.json",
}


def short(path: str) -> str:
    name = path[len("documentation/"):]
    if name.startswith("Combine/"):
        name = name[len("Combine/"):]
    name = name.rsplit(".json", 1)[0]
    name = re.sub(r"-swift\.(struct|class|enum|protocol|typealias)$", "", name)
    return name.replace("/", ".")


def is_type_page(path: str, rec: dict) -> bool:
    if rec.get("kind") != "symbol":
        return False
    last = short(path).split(".")[-1]
    if not re.match(r"^[A-Z]", last) or "(" in last:
        return False
    return True


def classify(path: str, name: str) -> str:
    if path.startswith("documentation/Foundation/"):
        for prefix, group in EXTERNAL_SCHEDULERS.items():
            if path.startswith(prefix):
                return group
        return "Foundation bridges"
    if path.startswith("documentation/Dispatch/"):
        return "Schedulers"
    simple = name.split(".")[-1]
    if simple in CORE:
        return "Core"
    if simple in SCHEDULERS:
        return "Schedulers"
    if simple in SUBJECTS:
        return "Subjects"
    if simple in VALUE_PUBLISHERS:
        return "Value publishers"
    if simple in STATE:
        return "State"
    if simple in ASYNC:
        return "Async interop"
    if name.startswith("Subscribers."):
        return "Subscribers"
    if name.startswith("Publishers.") or name == "Publishers":
        return "Publishers"
    return "Core"


def normalize(decl: str) -> str:
    return re.sub(r"\s+", " ", decl).strip()


def main() -> int:
    check = "--check" in sys.argv
    inv = json.loads(INVENTORY.read_text(encoding="utf-8"))
    pages = inv["pages"]

    types = {p: r for p, r in sorted(pages.items()) if is_type_page(p, r)}
    groups = {g: [] for g in GROUP_ORDER}
    for path, rec in sorted(types.items(), key=lambda kv: short(kv[0])):
        groups[classify(path, short(path))].append((path, rec))

    lines = [
        "# API reference (generated)",
        "",
        "> Generated by `Tools/gen_api_reference.py` from the DocC crawl",
        "> (`docs/api-inventory.json`) — **do not edit by hand**.",
        "> Regenerate with `python3 Tools/gen_api_reference.py`; every",
        "> listed declaration is verified against `Sources/LinuxCombine` by",
        "> `Tools/verify_decls.py`.",
        "",
    ]
    n_members = 0
    toc = []
    body = []
    for group in GROUP_ORDER:
        entries = groups[group]
        if not entries:
            continue
        anchor = group.lower().replace(" ", "-")
        toc.append(f"- [{group}](#{anchor}) ({len(entries)} types)")
        body.append(f"## {group}")
        body.append("")
        for path, rec in entries:
            name = short(path)
            decls = [normalize(d) for d in (rec.get("decls") or [])]
            body.append(f"### `{name}`")
            body.append("")
            if decls:
                body.append("```swift")
                body.extend(decls[:1])
                body.append("```")
                body.append("")
            sections = list(rec.get("sections", []))
            article = EXTENSION_ARTICLES.get(name)
            if article and article in pages:
                sections += pages[article].get("sections", [])
            for section in sections:
                members = []
                for member_path in section.get("members", []):
                    mrec = pages.get(member_path)
                    if not mrec or mrec.get("kind") == "missing":
                        continue
                    mdecls = [normalize(d) for d in (mrec.get("decls") or [])]
                    if not mdecls:
                        continue
                    if is_type_page(member_path, mrec):
                        nested = short(member_path)
                        members.append(f"- nested type `{nested}` (see below)")
                        continue
                    members.append(f"- `{mdecls[0]}`")
                if members:
                    n_members += len(members)
                    body.append(f"**{section['title']}**")
                    body.append("")
                    body.extend(members)
                    body.append("")
        body.append("")

    lines.append(f"{len(types)} types, {n_members} member declarations.")
    lines.append("")
    lines.append("## Contents")
    lines.append("")
    lines.extend(toc)
    lines.append("")
    lines.extend(body)

    text = "\n".join(lines).rstrip() + "\n"

    if check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("API-REFERENCE.md is STALE — regenerate with "
                  "python3 Tools/gen_api_reference.py")
            return 1
        print(f"API-REFERENCE.md up to date ({len(types)} types, "
              f"{n_members} members)")
        return 0

    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(types)} types, "
          f"{n_members} members")
    return 0


if __name__ == "__main__":
    sys.exit(main())
